const scopedQueueAccess = ({ req }: { req: { user?: unknown } }) => {
  if (isAdmin(req.user)) return true
  if (!hasFeature(req.user, 'actionQueue')) return false
  const features = getGrantedFeatureKeys(req.user).filter(
    (key) => key !== 'actionQueue' && key !== 'auditLog',
  )
  return features.length > 0 ? { feature: { in: features } } : false
}

const systemManagedFieldAccess = {
  create: () => false,
  update: () => false,
}

const syncOperatorResolutionMetadata: CollectionBeforeChangeHook = ({
  data,
  operation,
  originalDoc,
  req,
}) => {
  if (
    operation !== 'update' ||
    !data ||
    isWorkQueueSyncContext(req.context as Record<string, unknown> | undefined)
  ) {
    return data
  }

  const previousStatus = originalDoc?.status
  const nextStatus = data.status ?? previousStatus
  const terminal = nextStatus === 'resolved' || nextStatus === 'canceled'
  const wasTerminal = previousStatus === 'resolved' || previousStatus === 'canceled'

  if (terminal && !wasTerminal) {
    data.autoResolved = false
    data.resolvedAt = new Date().toISOString()
  } else if (!terminal && wasTerminal) {
    data.autoResolved = false
    data.resolvedAt = null
  }

  return data
}

